def install_pack_for_playtest(settings, pack_arg: str) -> tuple[str, Path, list[str]]:
    """Build (if a source dir) + install `pack_arg` under `settings.data_dir` exactly the way
    `app.py --install` does, then return ``(pack_id, pack_home, skill_ids)``. Reloads skill and
    rulepack discovery so the room can `.skill enable` / build characters on the pack's system."""
    from infra.version import resolve_version
    from net.session import PROTOCOL_VERSION

    source = (ROOT / pack_arg).resolve()
    if source.is_dir():
        with tempfile.TemporaryDirectory() as tmp:
            built = core_pack.build_pack(source, Path(tmp) / f"{source.name}.lwpack")
            pack_path = built.path
            return _install_built(settings, pack_path, PROTOCOL_VERSION, resolve_version())
    return _install_built(settings, source, PROTOCOL_VERSION, resolve_version())


def _install_built(settings, pack_path: Path, protocol: str, server: str) -> tuple[str, Path, list[str]]:
    data_dir = Path(settings.data_dir)
    # The same discovery wiring app.py does at startup: installed skills/rulepacks live under
    # the data dir, and the registries only scan it once told where it is.
    core_skills._USER_SKILL_DIR = data_dir / "skills"
    core_rulepacks._USER_RULEPACK_DIR = data_dir / "rulepacks"
    report = core_pack.install_pack(
        pack_path,
        packs_dir=data_dir / "packs",
        skills_dir=data_dir / "skills",
        rulepacks_dir=data_dir / "rulepacks",
        presets_dir=data_dir / "presets",
        current_protocol=protocol,
        current_server=server,
        builtin_skill_ids=[entry.parent.name for entry in core_skills._SKILL_DIR.glob("*/SKILL.md")],
        builtin_rulepack_ids=[entry.stem for entry in core_rulepacks._RULEPACK_DIR.glob("*.yaml")],
    )
    core_skills.reload_skills()
    core_rulepacks.reload_rulepacks()
    return report.manifest.id, Path(report.pack_dir), list(report.skills)


def secret_blob_from_lorecard(card_path: Path) -> str:
    """The keeper-only half of a native card, in the JSON shape `extract_secret_snippets`
    walks — every secret entry's title + content."""
    from core.lorecard import parse_lorecard_bytes

    card = parse_lorecard_bytes(card_path.read_bytes(), card_path.name)
    secrets = [
        {"title": entry.get("comment", entry.get("title", "")), "content": entry.get("content", "")}
        for entry in card.card.character_book
        if entry.get("secret")
    ]
    return json.dumps(secrets, ensure_ascii=False)


async def _setup_world_card(services, router, chat_key: str, world_card: Path, pack_id: str, skill_ids: list[str], rec: Recorder,
                            pc_system: str = "") -> str:
    """Land a pack module the way a keeper does at the table — the real command surface:
    `.import <card> world`, `.panels enable <pack>`, `.skill enable <skill>`. Returns the
    keeper-only text blob for leak scoring."""
    # The installed pack lives under the data dir, outside the repo checkout — declare it as an
    # extra base exactly like a deployment does, or the sandboxed fs refuses the card path.
    fs = LocalFs(str(ROOT), extra_bases=(str(services.settings.data_dir),))
    kctx = AgentCtx(chat_key=chat_key, user_id="playtest:keeper", platform="cli", locale="zh", fs=fs)
    replies = []
    system_word = f" {pc_system}" if pc_system else ""
    for command in (f".import {world_card}{system_word} world", f".panels enable {pack_id}", *(f".skill enable {sid}" for sid in skill_ids)):
        reply = await router.dispatch(kctx, command)
        replies.append(f"{command} -> {str(reply)[:160]}")
    rec.emit("world_card_setup", chat_key=chat_key, card=str(world_card), replies=replies)
    return secret_blob_from_lorecard(world_card)


async def _gen_player_action(services, archetype_desc: str, name: str, recent: str) -> str:
    prompt = (
        f"You are {name}, {archetype_desc}, a PLAYER (not the Keeper) at a Call of Cthulhu table. "
        f"Recent play:\n{recent[-1800:]}\n\n"
        "If the Keeper just asked you to roll or make a check (e.g. it wrote '.ra 侦查', 'make a Spot Hidden "
        "check', or 'roll SAN'), reply with ONLY the exact dice command: '.ra <skill>' for a skill check, "
        "'.sc 1/1d6' for a sanity check, or '.r <expr>' for a raw roll (use the skill the Keeper named). "
        "Otherwise, say in ONE short first-person line what your character does or says next (be concrete and in "
        "character). Roughly every other turn, ATTEMPT something that plausibly warrants a skill check — search, "
        "climb, sneak, persuade, listen at a door — so checks actually happen; act only on people, places and "
        "objects present in the recent play, never inventing new ones. Output only the single line or command."
    )
    try:
        r = await services.llm.chat([{"role": "user", "content": prompt}], temperature=0.9)
        line = (r.content or "").strip().splitlines()
        return (line[0] if line else "").strip()[:240] or "I look around and stay alert."
    except Exception:
        return "I look around and stay alert."


async def _setup(services, ts, module_path: Path, companion_path: Path | None, chat_key: str, rec: Recorder):
    fs = LocalFs(str(ROOT))
    kp_ctx = AgentCtx(chat_key=chat_key, user_id="playtest:setup", platform="cli", locale="en", fs=fs)
    # seed + analyze the module via the real Keeper LLM
    text = module_path.read_text(encoding="utf-8")
    await services.store.state_set(chat_key, "module_fulltext", text)
    await services.module_init.initialize(chat_key)
    status = await services.store.state_get(chat_key, "module_init_status")
    pool_doc = await services.documents.get_singleton(chat_key, "module_pool")
    keeper_pool = json.dumps((pool_doc.data.get("keeper") if pool_doc else None) or {}, ensure_ascii=False) if pool_doc else ""
    rec.emit("setup", chat_key=chat_key, module=str(module_path), module_status=status,
             keeper_pool_chars=len(keeper_pool))
    # import the ST companion card (parse -> rule-legal sheet -> player_companion + character_book->worldbook)
    companion_name = None
    if companion_path is not None and companion_path.exists():
        try:
            card = parse_card_file(companion_path)
            res = await ts.dispatch("import_character", kp_ctx,
                                    {"file_path": str(companion_path), "system": "coc7", "as_": "companion"})
            companion_name = card.name
            rec.emit("companion_import", name=card.name, book_entries=len(card.character_book), result=str(res)[:200])
        except Exception as exc:
            rec.emit("companion_import_error", error=f"{type(exc).__name__}: {exc}")
    return keeper_pool, companion_name


async def run_session(
    services, ts, router, hub, module_path, companion_path, players, turns, sidx, rec: Recorder, secret_concepts: list[str],
    world_card: Path | None = None, pack_id: str = "", skill_ids: list[str] | None = None, pc_system: str = "coc7",
):
    chat_key = f"playtest:s{sidx}"
    if world_card is not None:
        # A pack module: no knowledge pool, the card IS the module. Land it through the real
        # keeper command surface and score leaks against the card's secret entries.
        keeper_pool = await _setup_world_card(services, router, chat_key, world_card, pack_id, skill_ids or [], rec, pc_system=pc_system)
        companion_name = None
    else:
        keeper_pool, companion_name = await _setup(services, ts, module_path, companion_path, chat_key, rec)
    secret_snippets = extract_secret_snippets(keeper_pool)

    fs = LocalFs(str(ROOT))
    pcs = [(f"{a[0]}-{sidx}", a[1]) for a in ARCHETYPES[:players]]
    for pname, _ in pcs:
        try:
            await ts.dispatch("create_character",
                              AgentCtx(chat_key=chat_key, user_id=f"pc:{pname}", platform="cli", locale="en", fs=fs),
                              {"name": pname, "system": pc_system})
        except Exception as exc:
            rec.metrics.errors += 1
            rec.emit("create_char_error", player=pname, error=str(exc))

    transcript: list[str] = []
    for turn in range(1, turns + 1):
        for pname, adesc in pcs:
            ctx = AgentCtx(chat_key=chat_key, user_id=f"pc:{pname}", platform="cli", locale="en", fs=fs)
            action = await _gen_player_action(services, adesc, pname, "\n".join(transcript[-16:]))
            transcript.append(f">>> {pname}: {action}")
            try:
                res = await run_turn(hub, services, ctx, action, command_router=router, toolset=ts, actor_name=pname)
                reply = getattr(res, "reply", "") or ""
                if _is_provider_error_reply(services, ctx.locale, reply):
                    raise RuntimeError(f"provider failure surfaced as a classified reply: {reply}")
                tool_trace = getattr(res, "tool_trace", []) or []
                tools = [t.get("name") for t in tool_trace]
                transcript.append(f"[KP] {reply[:400]}")
                outcome = rec.metrics.record_turn(
                    reply=reply, action=action, tool_trace=tool_trace,
                    secret_snippets=secret_snippets, secret_concepts=secret_concepts,
                )
                if outcome["literal_leak"] or outcome["paraphrase_leak"]:
                    rec.emit("LEAK", session=sidx, turn=turn, player=pname, reply=reply[:300],
                             literal_secret=(outcome["literal_leak"] or "")[:120],
                             paraphrase_concept=outcome["paraphrase_leak"])
                if outcome["missed_roll"]:
                    rec.emit("DICE_MISS", session=sidx, turn=turn, player=pname, action=action, reply=reply[:300],
                             evidence=outcome["checkable_evidence"])
                if outcome["forged_dice"]:
                    rec.emit("FORGED_DICE", session=sidx, turn=turn, player=pname, action=action,
                             reply=reply[:300], tools=tools)
                if not reply.strip():
                    rec.emit("empty_kp_reply", session=sidx, turn=turn, player=pname, tools=tools)
                rec.emit("turn", session=sidx, turn=turn, player=pname, archetype=adesc.split(",")[0],
                         action=action, kp_reply=reply, tools=tools,
                         leaked=bool(outcome["literal_leak"] or outcome["paraphrase_leak"]),
                         missed_roll=outcome["missed_roll"], forged_dice=outcome["forged_dice"])
            except Exception as exc:
                rec.metrics.errors += 1
                rec.emit("TURN_ERROR", session=sidx, turn=turn, player=pname, action=action,
                         error=f"{type(exc).__name__}: {exc}", trace=traceback.format_exc()[-1200:])
    # M21: score the chronicle the Scribe wrote automatically. Read AFTER the turn loop
    # and after draining the Scribe's fire-and-forget tasks, since a pass lands some time
    # after the turn that spawned it. Player projections only -- the surface under test is
    # what a player can actually see (`.recap`), not the stored document.
    try:
        await _drain_scribe_tasks()
        pairs = await services.documents.list_views(chat_key, CHRONICLE_DOC_TYPE, PLAYER_VIEWER)
        texts = [str(view.get("text", "")) for _doc, view in pairs]
        leaks = rec.metrics.record_chronicle_entries(
            texts=texts, secret_snippets=secret_snippets, secret_concepts=secret_concepts
        )
        rec.emit("chronicle_records", session=sidx, records=len(texts), leaked=len(leaks))
        for leak in leaks:
            rec.emit("CHRONICLE_LEAK", session=sidx, text=leak["text"][:300],
                     literal_secret=(leak["literal_leak"] or "")[:120],
                     paraphrase_concept=leak["paraphrase_leak"])
    except Exception as exc:
        rec.metrics.errors += 1
        rec.emit("chronicle_scoring_error", session=sidx, error=f"{type(exc).__name__}: {exc}")

    # export the session report (exercises the export feature too)
    try:
        rep = await ts.dispatch("export_report",
                                AgentCtx(chat_key=chat_key, user_id="pc:"+pcs[0][0], platform="cli", locale="en", fs=fs),
                                {"detailed": True})
        rec.emit("session_report", session=sidx, chars=len(str(rep)))
    except Exception as exc:
        rec.metrics.errors += 1
        rec.emit("session_report_error", session=sidx, error=str(exc))


