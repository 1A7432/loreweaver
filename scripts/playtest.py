def _is_provider_error_reply(services: Any, locale: str, reply: str) -> bool:
    i18n = services.i18n.with_locale(locale)
    normalized = reply.strip()
    return any(normalized == i18n.t(key) for key in _PROVIDER_ERROR_KEYS)


def render_report(name: str, metrics: RedlineMetrics, thresholds: GateThresholds, passed: bool, reasons: list[str]) -> str:
    binding = (
        f"rate rule, max {thresholds.max_dice_miss_rate:.1%}"
        if metrics.checkable_turns >= thresholds.min_checkable_turns
        else f"absolute rule, max {thresholds.max_absolute_dice_misses} miss(es) "
        f"(< {thresholds.min_checkable_turns} checkable turns)"
    )
    lines = [
        f"=== {name} red-line gate ===",
        f"turns={metrics.turns}  errors={metrics.errors}  empty_kp_replies={metrics.empty_kp}",
        f"leak rate:      {metrics.leak_rate:6.1%}  ({metrics.leak_turns}/{metrics.turns} turns; "
        f"{metrics.literal_leaks} literal, {metrics.paraphrase_leaks} paraphrase)  "
        f"[max {thresholds.max_leak_rate:.1%}]",
        f"dice-miss rate: {metrics.dice_miss_rate:6.1%}  ({metrics.missed_roll_turns}/{metrics.checkable_turns} checkable turns)  "
        f"[{binding}]",
        f"forged dice:    {metrics.forged_dice_rate:6.1%}  ({metrics.forged_dice_turns}/{metrics.turns} turns)  "
        f"[max {thresholds.max_forged_dice_rate:.1%}]",
    ]
    # A missed roll is only a finding if its turn was correctly judged checkable,
    # so print the evidence behind every miss -- that is what the nightly false
    # positive lacked when a human had to decide whether to trust the number.
    misses = [item for item in metrics.checkable_evidence if item.get("missed_roll")]
    for item in misses[:10]:
        lines.append(f"  miss: skill={item['skill']!r} via {item['rule']} ({item['source']}) -- {item['quote']!r}")
    lines.append("PASS" if passed else "FAIL: " + "; ".join(reasons))
    return "\n".join(lines)


def write_summary_json(
    path: Path,
    name: str,
    metrics: RedlineMetrics,
    thresholds: GateThresholds,
    passed: bool,
    reasons: list[str],
    usage: UsageTotals | None = None,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "name": name,
        "passed": passed,
        "reasons": reasons,
        "counts": asdict(metrics),
        "rates": {
            "leak_rate": metrics.leak_rate,
            "dice_miss_rate": metrics.dice_miss_rate,
            "forged_dice_rate": metrics.forged_dice_rate,
        },
        "thresholds": asdict(thresholds),
    }
    if usage is not None:
        payload["usage"] = asdict(usage)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


def parse_secret_concepts(cli_value: str, file_value: str) -> list[str]:
    """Merge `--secret-concepts` (comma-separated) and `--secret-concepts-file`
    (one phrase per line) into a single deduplicated list. Both are optional;
    an empty result means only literal-leak detection runs (still meaningful --
    see `extract_secret_snippets` -- paraphrase sentinels are necessarily
    specific to whatever module is under test)."""
    concepts: list[str] = []
    if cli_value:
        concepts.extend(part.strip() for part in cli_value.split(",") if part.strip())
    if file_value:
        p = Path(file_value)
        if p.exists():
            concepts.extend(line.strip() for line in p.read_text(encoding="utf-8").splitlines() if line.strip())
    seen: set[str] = set()
    out: list[str] = []
    for c in concepts:
        if c not in seen:
            seen.add(c)
            out.append(c)
    return out


