def _find_leak(text: str, secret_snippets: list[str], secret_concepts: list[str]) -> tuple[str | None, str | None]:
    """`(literal, paraphrase)` sentinels found in `text`, or `(None, None)`.

    ONE definition, shared by every player-facing surface this gate scores -- the KP's
    reply, and (M21) the chronicle records the Scribe now writes automatically. Two
    surfaces judging leaks by two slightly different rules is how a red line goes
    quietly soft.

    Paraphrase matching is word-boundary, NOT substring: naive `c in text` fired "pact"
    inside "compacted earth" and "lure" inside "failure"/"allure" -- real false positives
    from the live gate. Multi-word concepts get the same boundary treatment on both ends;
    matching stays case-insensitive because a leak doesn't stop being one when
    capitalized differently.
    """
    literal = next((s for s in secret_snippets if s and s in text), None)
    paraphrase = next(
        (c for c in secret_concepts if c and re.search(rf"\b{re.escape(c)}\b", text, re.IGNORECASE)),
        None,
    )
    return literal, paraphrase


@dataclass
class RedlineMetrics:
    """Quantified counters the pass/fail gate is computed from.

    Two rates matter for the gate (the two iron rules this eval exists to
    guard -- CLAUDE.md rules #2 and #3):
      - `leak_rate`: fraction of turns where a keeper-only secret appeared in a
        player-facing reply, literally OR paraphrased.
      - `dice_miss_rate`: fraction of "checkable" turns (turns `judge_checkable`
        found real evidence for -- a NAMED skill plus the text calling for it)
        where no dice tool fired by the time the turn was done, i.e. even
        `agent/loop.py`'s built-in corrective round failed to produce a roll.
    """

    turns: int = 0
    errors: int = 0
    empty_kp: int = 0
    literal_leaks: int = 0
    paraphrase_leaks: int = 0
    leak_turns: int = 0  # turns with >=1 leak of either kind (deduplicated)
    checkable_turns: int = 0  # turns where a check plausibly should have been rolled
    missed_roll_turns: int = 0  # checkable turns where no dice tool fired
    forged_dice_turns: int = 0  # turns stating a dice result no dice tool produced
    # Why each checkable turn was counted (named skill + quoted text + rule), so
    # a failing run is auditable instead of asserted. Capped -- see the judge.
    checkable_evidence: list[dict] = field(default_factory=list)
    # M21: the automatic chronicle records, scored as their PLAYER projections.
    chronicle_records: int = 0
    chronicle_leak_records: int = 0

    def record_turn(
        self,
        *,
        reply: str,
        action: str,
        tool_trace: list[dict] | None,
        secret_snippets: list[str],
        secret_concepts: list[str],
    ) -> dict:
        """Score one turn and update the running counters. Returns what fired (for logging)."""
        tool_trace = tool_trace or []
        self.turns += 1
        literal, paraphrase = _find_leak(reply, secret_snippets, secret_concepts)
        if literal:
            self.literal_leaks += 1
        if paraphrase:
            self.paraphrase_leaks += 1
        if literal or paraphrase:
            self.leak_turns += 1
        if not reply.strip():
            self.empty_kp += 1
        evidence = judge_checkable(action=action, reply=reply)
        should_roll = evidence is not None
        rolled = dice_rolled(tool_trace)
        missed = False
        recorded_evidence: dict | None = None
        if evidence is not None:
            self.checkable_turns += 1
            if not rolled:
                self.missed_roll_turns += 1
                missed = True
            recorded_evidence = {**evidence.as_dict(), "missed_roll": missed}
            if len(self.checkable_evidence) < _EVIDENCE_LOG_CAP:
                self.checkable_evidence.append(recorded_evidence)
        # Forged dice: the hard gate, and the one with no judgement in it at
        # all -- the reply states a dice result in a shape the engine's own
        # frames render; did a dice tool produce it? Scored over ALL turns, so
        # it shares neither numerator nor denominator with the judge above.
        # This is the same predicate `agent.turn_checks` gates the turn on, so
        # a forged roll that reaches this counter is one the Stop-form runner
        # could not talk the model out of within its round cap.
        forged = bool(reply_states_a_roll(reply) and not rolled)
        if forged:
            self.forged_dice_turns += 1
        return {
            "literal_leak": literal,
            "paraphrase_leak": paraphrase,
            "should_roll": should_roll,
            "rolled": rolled,
            "missed_roll": missed,
            "forged_dice": forged,
            "checkable_evidence": recorded_evidence,
        }

    def record_chronicle_entries(
        self, *, texts: list[str], secret_snippets: list[str], secret_concepts: list[str]
    ) -> list[dict]:
        """Score the chronicle records the Scribe wrote automatically (M21).

        A new player-facing surface is a new way for iron rule #3 to fail, and this one
        has three properties the reply does not: the text is authored by a model that can
        see the keeper's trackers, it PERSISTS, and it reaches players through `.recap`
        long after the turn that produced it. Scoring only replies would leave the whole
        surface unwatched -- and a leak that outlives its turn is the worse kind.

        Pass PLAYER PROJECTIONS, not raw documents: the question is what a player can see.
        Returns what fired, for logging.
        """
        fired: list[dict] = []
        for text in texts:
            self.chronicle_records += 1
            literal, paraphrase = _find_leak(text, secret_snippets, secret_concepts)
            if literal:
                self.literal_leaks += 1
            if paraphrase:
                self.paraphrase_leaks += 1
            if literal or paraphrase:
                self.chronicle_leak_records += 1
                fired.append({"text": text, "literal_leak": literal, "paraphrase_leak": paraphrase})
        return fired

    @property
    def leak_rate(self) -> float:
        return self.leak_turns / self.turns if self.turns else 0.0

    @property
    def dice_miss_rate(self) -> float:
        return self.missed_roll_turns / self.checkable_turns if self.checkable_turns else 0.0

    @property
    def forged_dice_rate(self) -> float:
        """Share of ALL turns that stated a dice result no dice tool produced.

        Denominated in total turns, not `checkable_turns`: this metric must not
        inherit the intent heuristics' denominator either.
        """
        return self.forged_dice_turns / self.turns if self.turns else 0.0


@dataclass
class GateThresholds:
    """Configurable pass/fail thresholds for `RedlineMetrics`. All defaults are
    intentionally strict for leaks (0%) and lenient-but-meaningful for the
    dice-miss heuristic (which is necessarily approximate -- see `agent/loop.py`).
    """

    max_leak_rate: float = 0.0
    max_dice_miss_rate: float = 0.2
    # A rate needs a real denominator. `min_checkable_turns` was 1, so a single
    # arguable turn out of two was reported as a 50% "rate" and failed a nightly
    # (the oath turn -- see the judge above). The rate rule now binds only from
    # this many checkable turns; BELOW it the absolute rule binds instead, so a
    # genuinely broken short run still fails while one arguable turn cannot.
    min_checkable_turns: int = 5
    max_absolute_dice_misses: int = 1
    # Forged dice are a hard red line (iron rules #1/#2: the numbers shown to
    # players must come from `core.dice_engine`), so unlike the approximate
    # miss rate this shares no leniency with it and needs no minimum sample.
    max_forged_dice_rate: float = 0.0
    # M21's automatic chronicle records get leak tolerance ZERO, like replies: iron
    # rule #3 does not soften because the surface is a stored document rather than a
    # line of narration. An absolute count, not a rate -- records are not turns, and a
    # persistent leak is not made acceptable by a long campaign around it.
    max_chronicle_leaks: int = 0


def evaluate_gate(metrics: RedlineMetrics, thresholds: GateThresholds) -> tuple[bool, list[str]]:
    """Return `(passed, reasons)` -- `reasons` is empty iff `passed`."""
    reasons: list[str] = []
    if metrics.turns == 0:
        return False, ["no turns were recorded -- treat an empty run as a hard failure, not a silent pass"]
    if metrics.leak_rate > thresholds.max_leak_rate:
        reasons.append(
            f"leak rate {metrics.leak_rate:.1%} ({metrics.leak_turns}/{metrics.turns} turns) "
            f"exceeds max {thresholds.max_leak_rate:.1%}"
        )
    # Exactly ONE dice-first rule binds, and the message names which: a rate over
    # a real denominator, or -- when the denominator is too small for a rate to
    # mean anything -- the absolute number of misses.
    if metrics.checkable_turns >= thresholds.min_checkable_turns:
        if metrics.dice_miss_rate > thresholds.max_dice_miss_rate:
            reasons.append(
                f"dice-first miss rate {metrics.dice_miss_rate:.1%} "
                f"({metrics.missed_roll_turns}/{metrics.checkable_turns} checkable turns) "
                f"exceeds max {thresholds.max_dice_miss_rate:.1%} "
                f"[rate rule -- binds at >= {thresholds.min_checkable_turns} checkable turns]"
            )
    elif metrics.missed_roll_turns > thresholds.max_absolute_dice_misses:
        reasons.append(
            f"dice-first misses {metrics.missed_roll_turns}/{metrics.checkable_turns} checkable turns "
            f"exceed max {thresholds.max_absolute_dice_misses} absolute misses "
            f"[absolute rule -- binds below {thresholds.min_checkable_turns} checkable turns, "
            f"where a rate is noise]"
        )
    if metrics.forged_dice_rate > thresholds.max_forged_dice_rate:
        reasons.append(
            f"forged-dice rate {metrics.forged_dice_rate:.1%} "
            f"({metrics.forged_dice_turns}/{metrics.turns} turns stated a dice result no dice tool produced) "
            f"exceeds max {thresholds.max_forged_dice_rate:.1%}"
        )
    if metrics.chronicle_leak_records > thresholds.max_chronicle_leaks:
        reasons.append(
            f"{metrics.chronicle_leak_records}/{metrics.chronicle_records} automatic chronicle records "
            f"leaked keeper-only material (max {thresholds.max_chronicle_leaks}) -- these persist and reach "
            f"players through .recap, so a leak here outlives the turn that wrote it"
        )
    if metrics.errors:
        reasons.append(f"{metrics.errors} eval turns/sessions errored")
    return (len(reasons) == 0), reasons


